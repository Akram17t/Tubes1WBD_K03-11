CREATE TABLE migration_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_id BIGINT NOT NULL REFERENCES migrations (id) ON DELETE RESTRICT,
    executed_by BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    sql_snapshot TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'running' CHECK (
        status IN ('running', 'success', 'failed')
    ),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    error_message TEXT,
    CHECK (finished_at >= started_at)
);

CREATE INDEX migration_executions_migration_id_idx ON migration_executions (migration_id);
CREATE INDEX migration_executions_executed_by_idx ON migration_executions (executed_by);

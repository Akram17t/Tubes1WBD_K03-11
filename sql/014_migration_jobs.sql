-- M2: queue persisten di database platform. Worker mengklaim baris dengan FOR UPDATE SKIP LOCKED.
BEGIN;

CREATE TABLE migration_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Satu request approved hanya punya satu job: klik Eksekusi berulang mengembalikan job yang sama.
    request_id BIGINT NOT NULL UNIQUE REFERENCES migration_requests (id) ON DELETE RESTRICT,
    database_id BIGINT NOT NULL REFERENCES database_connections (id) ON DELETE RESTRICT,
    migration_id BIGINT NOT NULL REFERENCES migrations (id) ON DELETE RESTRICT,
    revision INTEGER NOT NULL CHECK (revision > 0),
    operation VARCHAR(20) NOT NULL CHECK (operation IN ('up', 'rollback', 'forward', 'compensate')),
    execution_actor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'queued' CHECK (
        status IN ('queued', 'running', 'success', 'failed', 'compensated',
                   'partial', 'partially_reverted', 'outcome_unknown')
    ),
    -- attempt_count mencakup semua attempt; auto_attempt_count hanya retry otomatis (maksimum diatur worker)
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    auto_attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (auto_attempt_count >= 0),
    queued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    -- Heartbeat basi hanya menjadikan job kandidat recovery; worker_token memagari worker lama (fencing).
    heartbeat_at TIMESTAMPTZ,
    worker_id TEXT,
    worker_token TEXT,
    -- Hanya W3C trace context (traceparent/tracestate), tanpa cookie atau credential.
    trace_carrier JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(trace_carrier) = 'object'),
    compensation_job_id BIGINT UNIQUE REFERENCES migration_jobs (id) ON DELETE RESTRICT,
    -- Salinan progres untuk API; sumber kebenaran batch ada di ledger target.
    total_rows BIGINT CHECK (total_rows >= 0),
    committed_rows BIGINT NOT NULL DEFAULT 0 CHECK (committed_rows >= 0),
    committed_batches BIGINT NOT NULL DEFAULT 0 CHECK (committed_batches >= 0),
    reverted_rows BIGINT NOT NULL DEFAULT 0 CHECK (reverted_rows >= 0),
    reverted_batches BIGINT NOT NULL DEFAULT 0 CHECK (reverted_batches >= 0),
    last_cursor BIGINT,
    error_code VARCHAR(50),
    error_message TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (compensation_job_id IS NULL OR compensation_job_id <> id),
    CHECK (status <> 'running' OR (started_at IS NOT NULL AND worker_token IS NOT NULL)),
    CHECK (status NOT IN ('success', 'compensated') OR finished_at IS NOT NULL)
);

-- Satu database hanya menjalankan satu job pada satu waktu; database berbeda boleh paralel.
CREATE UNIQUE INDEX migration_jobs_one_running_per_database_idx
    ON migration_jobs (database_id) WHERE status = 'running';

-- Indeks klaim worker.
CREATE INDEX migration_jobs_claim_idx ON migration_jobs (next_attempt_at, id) WHERE status = 'queued';
-- Pencarian blocker: partial, partially_reverted, dan outcome_unknown menahan migration lain.
CREATE INDEX migration_jobs_blocker_idx ON migration_jobs (database_id)
    WHERE status IN ('partial', 'partially_reverted', 'outcome_unknown');
-- Pencarian heartbeat basi.
CREATE INDEX migration_jobs_running_heartbeat_idx ON migration_jobs (heartbeat_at) WHERE status = 'running';
CREATE INDEX migration_jobs_database_id_idx ON migration_jobs (database_id, id);
CREATE INDEX migration_jobs_migration_id_idx ON migration_jobs (migration_id);
CREATE INDEX migration_jobs_execution_actor_id_idx ON migration_jobs (execution_actor_id);

-- 013 sengaja menunda FK ini karena migration_jobs belum ada saat itu.
ALTER TABLE migration_requests
    ADD CONSTRAINT migration_requests_source_job_id_fkey
        FOREIGN KEY (source_job_id) REFERENCES migration_jobs (id) ON DELETE RESTRICT;

CREATE INDEX migration_requests_source_job_id_idx
    ON migration_requests (source_job_id) WHERE source_job_id IS NOT NULL;

COMMIT;

CREATE TABLE migrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_id BIGINT NOT NULL REFERENCES database_connections (id) ON DELETE RESTRICT,
    version BIGINT CHECK (version > 0),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    sql_content TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (
        status IN ('draft', 'running', 'success', 'failed')
    ),
    created_by BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (database_id, version),
    CHECK ((status = 'success') = (version IS NOT NULL))
);

CREATE INDEX migrations_created_by_idx ON migrations (created_by);

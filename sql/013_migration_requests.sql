BEGIN;

CREATE TABLE migration_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_id BIGINT NOT NULL REFERENCES database_connections (id) ON DELETE RESTRICT,
    migration_id BIGINT NOT NULL REFERENCES migrations (id) ON DELETE RESTRICT,
    revision INTEGER NOT NULL CHECK (revision > 0),
    operation VARCHAR(20) NOT NULL CHECK (operation IN ('up', 'rollback', 'forward', 'compensate')),
    target_execution_id BIGINT REFERENCES migration_executions (id) ON DELETE RESTRICT,
    -- shortcut: source_job_id FK awaits migration_jobs, add the constraint in SQL 014.
    source_job_id BIGINT CHECK (source_job_id > 0),
    review_status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (review_status IN ('draft', 'pending_review', 'approved', 'cancelled')),
    requested_by BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    definition_snapshot JSONB NOT NULL CHECK (jsonb_typeof(definition_snapshot) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at TIMESTAMPTZ,
    CHECK (
        (operation = 'up' AND target_execution_id IS NULL AND source_job_id IS NULL) OR
        (operation IN ('rollback', 'forward') AND target_execution_id IS NOT NULL AND source_job_id IS NULL) OR
        (operation = 'compensate' AND source_job_id IS NOT NULL AND target_execution_id IS NULL)
    ),
    CHECK (review_status NOT IN ('pending_review', 'approved') OR submitted_at IS NOT NULL)
);

CREATE INDEX migration_requests_database_id_idx ON migration_requests (database_id, created_at, id);
CREATE INDEX migration_requests_active_review_idx ON migration_requests (migration_id)
    WHERE review_status IN ('pending_review', 'approved');

CREATE TABLE migration_approvals (
    request_id BIGINT NOT NULL REFERENCES migration_requests (id) ON DELETE RESTRICT,
    group_id BIGINT NOT NULL REFERENCES groups (id) ON DELETE RESTRICT,
    group_name_snapshot VARCHAR(100) NOT NULL,
    approved_by BIGINT REFERENCES users (id) ON DELETE RESTRICT,
    approved_at TIMESTAMPTZ,
    PRIMARY KEY (request_id, group_id),
    CHECK ((approved_by IS NULL) = (approved_at IS NULL))
);

COMMIT;

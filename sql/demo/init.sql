BEGIN;

CREATE TABLE public.clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    city VARCHAR(100) NOT NULL,
    stadium VARCHAR(100)
);

CREATE TABLE public.players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES public.clubs (id) ON DELETE RESTRICT,
    squad_number SMALLINT NOT NULL CHECK (squad_number BETWEEN 1 AND 99),
    name VARCHAR(100) NOT NULL,
    position VARCHAR(2) NOT NULL CHECK (position IN ('GK', 'DF', 'MF', 'FW')),
    birth_date DATE NOT NULL,
    UNIQUE (club_id, squad_number)
);

CREATE TABLE public.matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_club_id BIGINT NOT NULL REFERENCES public.clubs (id) ON DELETE RESTRICT,
    away_club_id BIGINT NOT NULL REFERENCES public.clubs (id) ON DELETE RESTRICT,
    played_at TIMESTAMPTZ NOT NULL,
    home_goals SMALLINT NOT NULL CHECK (home_goals >= 0),
    away_goals SMALLINT NOT NULL CHECK (away_goals >= 0),
    CHECK (home_club_id <> away_club_id),
    UNIQUE (home_club_id, away_club_id, played_at)
);

CREATE TABLE public.appearances (
    match_id BIGINT NOT NULL REFERENCES public.matches (id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES public.players (id) ON DELETE RESTRICT,
    minutes_played SMALLINT NOT NULL CHECK (minutes_played BETWEEN 1 AND 120),
    rating NUMERIC(3, 1) CHECK (rating BETWEEN 0 AND 10),
    PRIMARY KEY (match_id, player_id)
);

CREATE INDEX matches_away_club_id_idx ON public.matches (away_club_id);
CREATE INDEX appearances_player_id_idx ON public.appearances (player_id);

COMMIT;
